import math

print(round(1.3))  # Redondea al número entero más cercano
print(round(2.9))  # Redondea al número entero más cercano
print(abs(-5))  # Devuelve el valor absoluto de un número

print(math.floor(1.999))  # Redondea hacia abajo al número entero más cercano
print(math.ceil(1.001))  # Redondea hacia arriba al número entero más cercano
print(
    math.isnan(1)
)  # Devuelve True si el valor es NaN (Not a Number), de lo contrario, devuelve False
print(
    math.pow(5, 3)
)  # Devuelve el resultado de elevar el primer número a la potencia del segundo número
print(math.sqrt(16))  # Devuelve la raíz cuadrada de un número
